import android.content.Context
import android.content.SharedPreferences
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * The phone's LANLink identity (certificate + private key), encrypted at
 * rest with an AES-256-GCM key that lives in the Android Keystore and never
 * leaves it. The identity blob is generated by the native library because
 * the TLS stack needs the raw key; the Keystore key protects it on disk.
 */
class IdentityStore(context: Context) {
    private val file = File(context.noBackupFilesDir, "identity.bin")
    private val alias = "lanlink-identity-wrap"

    @Volatile private var cached: ByteArray? = null

    private fun key(): SecretKey {
        val ks = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (ks.getKey(alias, null) as? SecretKey)?.let { return it }
        val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
        gen.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .build(),
        )
        return gen.generateKey()
    }

    /** Load the identity, creating it on first use. */
    @Synchronized
    fun get(deviceLabel: String): ByteArray {
        cached?.let { return it }
        if (file.exists()) {
            runCatching { decrypt(file.readBytes()) }.getOrNull()?.let {
                cached = it
                return it
            }
            // Undecryptable (e.g. Keystore reset by a device restore):
            // start over with a new identity; the PC will see a new phone.
            file.delete()
        }
        val id = NativeBridge.generateIdentity(deviceLabel)
        val tmp = File(file.parentFile, "identity.tmp")
        tmp.writeBytes(encrypt(id))
        tmp.renameTo(file)
        cached = id
        return id
    }

    fun fingerprint(deviceLabel: String): String = NativeBridge.identityFingerprint(get(deviceLabel))

    /** Forget the identity. Every PC will treat this phone as new. */
    @Synchronized
    fun clear() {
        cached = null
        file.delete()
        runCatching {
            KeyStore.getInstance("AndroidKeyStore").apply { load(null) }.deleteEntry(alias)
        }
    }

    private fun encrypt(plain: ByteArray): ByteArray {
        val c = Cipher.getInstance("AES/GCM/NoPadding")
        c.init(Cipher.ENCRYPT_MODE, key())
        val iv = c.iv
        val body = c.doFinal(plain)
        return byteArrayOf(1, iv.size.toByte()) + iv + body
    }

    private fun decrypt(blob: ByteArray): ByteArray {
        require(blob.size > 2 && blob[0] == 1.toByte())
        val ivLen = blob[1].toInt()
        val iv = blob.copyOfRange(2, 2 + ivLen)
        val c = Cipher.getInstance("AES/GCM/NoPadding")
        c.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(128, iv))
        return c.doFinal(blob, 2 + ivLen, blob.size - 2 - ivLen)
    }
}

/** A PC this phone has paired with. */
data class PairedHost(
    val fingerprint: String,
    val name: String,
    val addresses: List<String>,
    val port: Int,
    val pairedAt: Long,
    val lastConnected: Long,
) {
    /** First 16 hex digits; matches the mDNS `id` of the host. */
    val shortId: String get() = fingerprint.take(16)

    fun toJson(): JSONObject = JSONObject()
        .put("fp", fingerprint).put("name", name).put("addrs", JSONArray(addresses))
        .put("port", port).put("pairedAt", pairedAt).put("last", lastConnected)

    companion object {
        fun fromJson(o: JSONObject) = PairedHost(
            fingerprint = o.getString("fp"),
            name = o.optString("name", "PC"),
            addresses = o.optJSONArray("addrs")?.let { a -> List(a.length()) { a.getString(it) } } ?: emptyList(),
            port = o.optInt("port", 47990),
            pairedAt = o.optLong("pairedAt"),
            lastConnected = o.optLong("last"),
        )

        fun listToJson(hosts: List<PairedHost>): String = JSONArray(hosts.map { it.toJson() }).toString()

        fun listFromJson(s: String?): List<PairedHost> = runCatching {
            val a = JSONArray(s ?: "[]")
            List(a.length()) { fromJson(a.getJSONObject(it)) }
        }.getOrDefault(emptyList())
    }
}

/** Paired PCs. Fingerprints are public, but the list is kept app-private. */
class HostRepository(context: Context) {
    private val prefs: SharedPreferences = context.getSharedPreferences("hosts", Context.MODE_PRIVATE)

    @Synchronized fun all(): List<PairedHost> =
        PairedHost.listFromJson(prefs.getString("list", null)).sortedByDescending { it.lastConnected }

    @Synchronized fun get(fp: String): PairedHost? = all().firstOrNull { it.fingerprint == fp }

    @Synchronized fun put(h: PairedHost) {
        val list = all().filter { it.fingerprint != h.fingerprint } + h
        prefs.edit().putString("list", PairedHost.listToJson(list)).apply()
    }

    @Synchronized fun remove(fp: String) {
        prefs.edit().putString("list", PairedHost.listToJson(all().filter { it.fingerprint != fp })).apply()
    }

    @Synchronized fun clear() = prefs.edit().remove("list").apply()

    fun touch(fp: String, address: String) {
        val h = get(fp) ?: return
        val addrs = (listOf(address) + h.addresses).distinct().take(6)
        put(h.copy(addresses = addrs, lastConnected = System.currentTimeMillis()))
    }
}

enum class Quality(val wire: Int, val label: String) {
    SMOOTH(0, "Smooth"), BALANCED(1, "Balanced"), SHARP(2, "Sharp"), CUSTOM(3, "Custom")
}

/** User preferences. Plain values, no secrets. */
class Settings(context: Context) {
    private val p = context.getSharedPreferences("settings", Context.MODE_PRIVATE)

    var onboarded: Boolean
        get() = p.getBoolean("onboarded", false)
        set(v) = p.edit().putBoolean("onboarded", v).apply()
    var quality: Quality
        get() = runCatching { Quality.valueOf(p.getString("quality", "BALANCED")!!) }.getOrDefault(Quality.BALANCED)
        set(v) = p.edit().putString("quality", v.name).apply()
    var pointerMode: PointerMode
        get() = runCatching { PointerMode.valueOf(p.getString("pointer", "TRACKPAD")!!) }.getOrDefault(PointerMode.TRACKPAD)
        set(v) = p.edit().putString("pointer", v.name).apply()
    var sensitivity: Float
        get() = p.getFloat("sens", 1.0f)
        set(v) = p.edit().putFloat("sens", v).apply()
    var acceleration: Float
        get() = p.getFloat("accel", 0.5f)
        set(v) = p.edit().putFloat("accel", v).apply()
    /** Custom-mode values; 0 = automatic. */
    var customFps: Int
        get() = p.getInt("fps", 0)
        set(v) = p.edit().putInt("fps", v).apply()
    var customKbps: Int
        get() = p.getInt("kbps", 0)
        set(v) = p.edit().putInt("kbps", v).apply()
    var customMaxWidth: Int
        get() = p.getInt("maxw", 0)
        set(v) = p.edit().putInt("maxw", v).apply()
    var maxKbps: Int
        get() = p.getInt("maxkbps", 0)
        set(v) = p.edit().putInt("maxkbps", v).apply()
    var fillScreen: Boolean
        get() = p.getBoolean("fill", false)
        set(v) = p.edit().putBoolean("fill", v).apply()
    /** Use LANLink's compact keyboard instead of the phone's own. */
    var compactKeyboard: Boolean
        get() = p.getBoolean("compactKeyboard", true)
        set(v) = p.edit().putBoolean("compactKeyboard", v).apply()
    /** Key height of the compact keyboard in dp. */
    var keyHeight: Float
        get() = p.getFloat("keyHeight", 36f).coerceIn(28f, 48f)
        set(v) = p.edit().putFloat("keyHeight", v.coerceIn(28f, 48f)).apply()
    /**
     * Allow screenshots, screen recording and the Recents preview while the
     * PC is shown. Off by default: the PC screen often holds passwords,
     * banking pages and one-time codes.
     */
    var allowScreenshots: Boolean
        get() = p.getBoolean("allowShots", false)
        set(v) = p.edit().putBoolean("allowShots", v).apply()
    /** Session controls on the left edge instead of the right. */
    var controlsLeft: Boolean
        get() = p.getBoolean("controlsLeft", false)
        set(v) = p.edit().putBoolean("controlsLeft", v).apply()
    /** Turn the phone sideways while controlling (the PC is landscape). */
    var landscape: Boolean
        get() = p.getBoolean("landscape", true)
        set(v) = p.edit().putBoolean("landscape", v).apply()
    /** Zoom the view starts at in trackpad mode (1 = whole desktop). */
    var startZoom: Float
        get() = p.getFloat("startzoom", 2f)
        set(v) = p.edit().putFloat("startzoom", v.coerceIn(1f, 4f)).apply()
    var showStats: Boolean
        get() = p.getBoolean("stats", false)
        set(v) = p.edit().putBoolean("stats", v).apply()
    var keepScreenOn: Boolean
        get() = p.getBoolean("awake", true)
        set(v) = p.edit().putBoolean("awake", v).apply()
    var viewOnly: Boolean
        get() = p.getBoolean("viewonly", false)
        set(v) = p.edit().putBoolean("viewonly", v).apply()
    var deviceName: String
        get() = p.getString("devname", null) ?: defaultDeviceName()
        set(v) = p.edit().putString("devname", v.take(48)).apply()

    fun clear() = p.edit().clear().apply()

    companion object {
        fun defaultDeviceName(): String {
            val m = android.os.Build.MODEL ?: "Android phone"
            val brand = android.os.Build.MANUFACTURER?.replaceFirstChar { it.uppercase() } ?: ""
            return if (m.startsWith(brand, ignoreCase = true)) m else "$brand $m".trim()
        }
    }
}
